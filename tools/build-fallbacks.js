// Regenerates js/data/fallbacks.js: validated static exercises (per language) used only if live generation fails.
// Usage: node tools/build-fallbacks.js
const fs = require('fs'), path = require('path');
const RT = require('./load-engine')(['data/fallbacks', 'statistics', 'storage', 'timer', 'state']);
const out = {};
for (const lang of RT.i18n.LANGS) {
  out[lang] = {};
  for (const m of Object.keys(RT.modules)) {
    out[lang][m] = {};
    for (const lvl of [1, 2, 3]) {
      out[lang][m][lvl] = [];
      for (let i = 1; i <= 4; i++) {
        const ex = RT.generator.generateFromSeed(m, lvl, 'fallback' + i, { lang }).exercise;
        ex.id = `fallback-${m}-L${lvl}-${i}`;
        out[lang][m][lvl].push(ex);
      }
    }
  }
}
const text = `/* AUTO-GENERATED by tools/build-fallbacks.js — validated static exercises per language (fallback only). */\n(function () {\n  const RT = (globalThis.RT = globalThis.RT || {});\n  RT.fallbacks = ${JSON.stringify(out)};\n})();\n`;
fs.writeFileSync(path.join(__dirname, '..', 'js', 'data', 'fallbacks.js'), text);
console.log('fallbacks written', text.length, 'bytes');
